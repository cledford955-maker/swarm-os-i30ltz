#!/usr/bin/env bash
# =============================================================================
#  setup_syncthing  —  LUCILLE <-> 3 phones
#  Script version : 1.0.0            Date: 2026-09-07
#  Supersedes     : setup_syncthing.sh (pointed at /mnt/lucy/Luccile-v+)
#
#  Syncs the SMALL, high-value folders. ISOs, binaries and secrets stay put.
#  Run as your normal user (i30ltz). Sudo is used only for pacman.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DRIVE_ROOT="$(dirname "$SCRIPT_DIR")"

GREEN='\033[0;32m'; CYAN='\033[0;36m'; YELLOW='\033[1;33m'; BOLD='\033[1m'; NC='\033[0m'

# Folders offered to the phones: id | path | label
SYNC_FOLDERS=(
  "swarm-source|$DRIVE_ROOT/30-source|SWARM Source (Coder Droid workspace)"
  "boltz-brain|$DRIVE_ROOT/60-boltz-brain|Boltz Brain (Lucille memory)"
  "swarm-docs|$DRIVE_ROOT/90-docs|SWARM Docs"
  "swarm-scripts|$DRIVE_ROOT/70-scripts|SWARM Scripts"
)

# NEVER synced: 10-releases (multi-GB ISOs), 20-runtime (binaries + .env secrets),
# 99-archive. Add them by hand in the web UI if you really want them.

echo -e "${CYAN}${BOLD}=== Syncthing setup for LUCILLE -> 3 phones ===${NC}\n"
echo -e "  drive root: $DRIVE_ROOT\n"

if ! command -v syncthing >/dev/null 2>&1; then
  echo -e "${CYAN}==> Installing Syncthing...${NC}"
  sudo pacman -S --noconfirm syncthing
else
  echo -e "${GREEN}==> Syncthing already installed:${NC} $(syncthing --version | head -1)"
fi

echo -e "\n${CYAN}==> Enabling Syncthing user service...${NC}"
systemctl --user enable --now syncthing
sleep 3   # let it generate keys on first run

DEVICE_ID="$(syncthing --device-id 2>/dev/null || echo UNKNOWN)"

# Ignore patterns so phones never pull build junk
for entry in "${SYNC_FOLDERS[@]}"; do
  IFS='|' read -r fid fpath flabel <<< "$entry"
  mkdir -p "$fpath"
  # Never overwrite a tailored ignore file (30-source has a large one).
  if [ -f "$fpath/.stignore" ]; then
    echo "  keeping existing .stignore in $(basename "$fpath")"
    continue
  fi
  cat > "$fpath/.stignore" <<'IGN'
// generated by setup_syncthing 1.0.0
*.iso
*.qcow2
*.tar.gz
*.zip
.env
*.pdb
index/
logs/
**/build/
**/obj/
**/.dart_tool/
IGN
done

echo -e "\n${CYAN}${BOLD}======================================================================${NC}"
echo -e "${GREEN}${BOLD}  Syncthing is running — Web UI: http://127.0.0.1:8384${NC}"
echo -e "${CYAN}${BOLD}======================================================================${NC}"
echo -e "\n${BOLD}This machine's Device ID (give this to all 3 phones):${NC}\n"
echo -e "  ${BOLD}${DEVICE_ID}${NC}\n"

echo -e "${BOLD}Folders to add in the web UI:${NC}"
for entry in "${SYNC_FOLDERS[@]}"; do
  IFS='|' read -r fid fpath flabel <<< "$entry"
  printf "  %-16s %s\n" "$fid" "$fpath"
  printf "  %-16s label: %s\n\n" "" "$flabel"
done

cat <<'STEPS'
Steps on each of the 3 phones:
  1. Install "Syncthing-Fork" (Play Store) or "Syncthing" (F-Droid).
  2. Phone -> Devices -> "+" -> paste this machine's Device ID above.
  3. Back on LUCILLE, accept the incoming device request in the web UI,
     and name the phones distinctly (phone-1, phone-2, phone-3).
  4. For each folder listed above: Edit Folder -> Sharing -> tick all 3 phones.
  5. On the phone, accept the shared-folder prompt and pick a local path.
  6. Repeat 2-5 for phone 2 and phone 3.

Send Only / Receive Only:
  Set 60-boltz-brain to "Send & Receive" (memory should flow both ways).
  Set 70-scripts and 90-docs to "Send Only" from LUCILLE if you want the
  laptop to stay authoritative.

Tailscale:
  Once all 4 devices are on the tailnet, Syncthing finds the 100.x.x.x
  addresses and uses that tunnel automatically. No extra config.

30-source is the Coder Droid workspace. Its .stignore strips build output
(.dart_tool, build, bin, obj, .gradle) and takes it from 1.25 GB to ~40 MB.
On the phone, open Coder Droid -> folder picker -> the synced 30-source folder.

NOT SYNCED ON PURPOSE:
  10-releases/  multi-GB ISOs, would destroy phone storage and data plans
  20-runtime/   compiled binaries, and config/.env holds live API keys
  99-archive/   superseded material
STEPS
